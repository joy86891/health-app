/**
 * 根据运动天数获取随机话术
 * @param days 一周运动天数 (1-7)
 * @returns 随机话术
 */
export function getRandomQuote(days: number): string {
  const clampedDays = Math.max(1, Math.min(7, days || 1));
  const quotes = MOTIVATION_QUOTES[clampedDays];
  const randomIndex = Math.floor(Math.random() * quotes.length);
  return quotes[randomIndex];
}
